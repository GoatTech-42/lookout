#!/usr/bin/env python3
"""Generates dev.meshac.check.CheckDependencies with transitive context requirements.

Scans the ported source tree, builds a class-level reference graph over dev.meshac classes,
seeds direct dependencies (clientVersion reads / version-predicate helpers / WorldBlockTracker
access), propagates transitively, and emits static sets for ContextGate. A check missing from
the output is fail-closed (gated) by ContextGate.

Run after porting changes: python3 scripts/analyze_deps.py
"""
import os, re, sys

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'main', 'java', 'dev', 'meshac')
OUT = os.path.join(ROOT, 'check', 'CheckDependencies.java')

# direct-dependency markers (on the class's own source text)
VERSION_PATTERNS = [
    r'\.getClientVersion\s*\(',  # call sites only, not the PlayerData declaration
    r'\.isAtLeast1_1[37]\s*\(\s*\)',       # call sites only
    r'\.isNewerThan1_9\s*\(\s*\)',
    r'\.isOlderThan1_9\s*\(\s*\)',
    r'\.isAtLeast1_21_2\s*\(\s*\)',
]
WORLD_PATTERNS = [
    r'\.getWorldBlockTracker\s*\(',  # call sites only; declarations/comments do not seed
]

classes = {}  # simpleName -> dict(path, text, refs, needsVersion, needsWorld)
for dirpath, _, files in os.walk(ROOT):
    for fn in files:
        if not fn.endswith('.java'):
            continue
        path = os.path.join(dirpath, fn)
        text = open(path, encoding='utf-8').read()
        simple = fn[:-5]
        refs = set(re.findall(r'\b([A-Z][A-Za-z0-9_]*)\b', text))
        classes[simple] = {
            'path': path,
            'refs': refs,
            'needsVersion': any(re.search(p, text) for p in VERSION_PATTERNS),
            'needsWorld': any(re.search(p, text) for p in WORLD_PATTERNS),
        }

for name in classes:
    classes[name]['refs'] &= set(classes)  # internal edges only

# transitive propagation
changed = True
while changed:
    changed = False
    for name, info in classes.items():
        for ref in info['refs']:
            r = classes[ref]
            if r['needsVersion'] and not info['needsVersion']:
                info['needsVersion'] = True; changed = True
            if r['needsWorld'] and not info['needsWorld']:
                info['needsWorld'] = True; changed = True

# checks live under check/impl (mirrors upstream layout)
checks = sorted(
    name for name, info in classes.items()
    if os.sep + os.path.join('check', 'impl') + os.sep in info['path']
)
needs_v = [c for c in checks if classes[c]['needsVersion']]
needs_w = [c for c in checks if classes[c]['needsWorld']]

def javacset(name, items):
    body = ', '.join('"%s"' % c for c in items)
    return 'public static final java.util.Set<String> %s = new java.util.HashSet<>(java.util.Arrays.asList(%s));' % (name, body)

out = '''package dev.meshac.check;

/**
 * GENERATED by scripts/analyze_deps.py - do not edit by hand.
 * Static, transitively-propagated context requirements per check class (simple names).
 * Checks missing from KNOWN fail closed in ContextGate.
 */
public final class CheckDependencies {

	private CheckDependencies() {
	}

	%s

	%s

	%s
}
''' % (javacset('KNOWN', checks), javacset('NEEDS_CLIENT_VERSION', needs_v), javacset('NEEDS_WORLD_CACHE', needs_w))
open(OUT, 'w', encoding='utf-8').write(out)
print('checks:', len(checks), 'needsVersion:', len(needs_v), 'needsWorld:', len(needs_w))
