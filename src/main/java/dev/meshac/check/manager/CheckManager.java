	/** Builds the per-player check instances; gated checks are filtered by ContextGate at dispatch. */
	public static List<AbstractCheck> createChecks(PlayerData data) {
		List<AbstractCheck> checks = new ArrayList<>(checkTypes.length);
		for (Class<?> type : checkTypes) {
			try {
				checks.add((AbstractCheck) type.getConstructor(PlayerData.class).newInstance(data));
			} catch (ReflectiveOperationException e) {
				throw new IllegalStateException("cannot construct check " + type.getSimpleName(), e);
			}
		}
		return checks;
	}
