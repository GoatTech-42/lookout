package dev.meshac.packet;

/**
 * Packet identities the checks reason about, mirroring the packetevents PacketType.Play constants
 * Vulcan's checks test against. The dispatcher maps 26.3 protocol packets onto these.
 * SERVER_ prefix = clientbound (server -> client), everything else is serverbound.
 */
public enum MeshPacketType {
	// serverbound
	FLYING, // any ServerboundMovePlayerPacket variant (position/rotation/onGround only)
	POSITION,
	POSITION_ROTATION,
	ROTATION,
	GROUND_ONLY, // onGround-only flying variant
	VEHICLE_MOVE,
	STEER_VEHICLE,
	INTERACT_ENTITY,
	ENTITY_ACTION,
	PLAYER_DIGGING,
	PLAYER_BLOCK_PLACEMENT,
	USE_ITEM,
	HELD_ITEM_CHANGE,
	ANIMATION,
	KEEP_ALIVE,
	PONG,
	WINDOW_CONFIRMATION, // legacy container confirm; 26.x uses PONG/CONTAINER_ACK
	CONTAINER_ACK,
	TELEPORT_CONFIRM,
	CLICK_WINDOW,
	CLOSE_WINDOW,
	CLIENT_TICK_END,
	CHAT_MESSAGE,
	CHAT_COMMAND,
	UPDATE_SIGN,
	PLAYER_ABILITIES,
	CLIENT_INFORMATION,
	CLIENT_STATUS,
	CUSTOM_PAYLOAD,
	SET_CREATIVE_SLOT,
	RESOURCE_PACK_STATUS,
	PICK_ITEM,
	PLACE_RECIPE,
	RECIPE_BOOK_UPDATE,
	EDIT_BOOK,
	SIGN_UPDATE,
	PADDLE_BOAT,
	PLAYER_INPUT,
	SPECTATE,
	ADVANCEMENT_TAB,
	COMMAND_SUGGESTION,
	BLOCK_ENTITY_TAG_QUERY,
	ENTITY_TAG_QUERY,
	JIGSAW_GENERATE,
	SET_COMMAND_BLOCK,
	SET_COMMAND_MINECART,
	SET_JIGSAW,
	SET_STRUCTURE_BLOCK,
	UPDATE_PROGRAM_STRUCTURE_BLOCK,
	DEBUG_SAMPLE_SUBSCRIPTION,
	CHANGE_DIFFICULTY,
	LOCK_DIFFICULTY,
	TELEPORT_TO_ENTITY,
	// clientbound
	SERVER_POSITION, // ClientboundPlayerPositionPacket (teleport/setback)
	SERVER_KEEP_ALIVE,
	SERVER_PING, // ClientboundPingPacket (transaction-style id)
	SERVER_WINDOW_CONFIRMATION,
	SERVER_SET_SLOT,
	SERVER_WINDOW_ITEMS,
	SERVER_ENTITY_VELOCITY,
	SERVER_EXPLOSION,
	SERVER_ENTITY_METADATA,
	SERVER_ENTITY_EFFECT,
	SERVER_REMOVE_ENTITY_EFFECT,
	SERVER_UPDATE_ATTRIBUTES,
	SERVER_SPAWN_ENTITY,
	SERVER_SPAWN_POSITION,
	SERVER_BLOCK_UPDATE,
	SERVER_MULTI_BLOCK_UPDATE,
	SERVER_LEVEL_CHUNK,
	SERVER_UNLOAD_CHUNK,
	SERVER_BLOCK_BREAK_ACK,
	SERVER_OPEN_WINDOW,
	SERVER_CLOSE_WINDOW,
	SERVER_RESPAWN,
	SERVER_LOGIN,
	SERVER_DISCONNECT,
	SERVER_ENTITY_STATUS,
	SERVER_ABILITIES,
	SERVER_CHANGE_GAME_STATE,
	SERVER_UPDATE_TIME,
	SERVER_SOUND,
	SERVER_ENTITY_TELEPORT,
	SERVER_MOVE_ENTITY,
	SERVER_ROTATE_HEAD,
	SERVER_ANIMATION,
	SERVER_SYSTEM_CHAT,
	SERVER_PLAYER_INFO,
	UNKNOWN;

	public boolean isFlying() {
		return this == FLYING || this == POSITION || this == POSITION_ROTATION || this == ROTATION || this == GROUND_ONLY;
	}
}
